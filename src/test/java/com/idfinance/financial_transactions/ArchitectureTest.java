package com.idfinance.financial_transactions;

import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes;
import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses;
import static com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noFields;

import com.tngtech.archunit.base.DescribedPredicate;
import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import com.tngtech.archunit.core.domain.JavaMethod;
import com.tngtech.archunit.core.domain.JavaModifier;
import com.tngtech.archunit.core.importer.ClassFileImporter;
import com.tngtech.archunit.core.importer.ImportOption;
import com.tngtech.archunit.lang.ArchRule;
import com.tngtech.archunit.lang.conditions.ArchConditions;
import java.lang.annotation.Annotation;
import net.javacrumbs.shedlock.spring.annotation.SchedulerLock;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.springframework.cache.annotation.Cacheable;
import org.springframework.scheduling.annotation.Async;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

/**
 * Mechanical enforcement of the project conventions.
 *
 * <p>
 * This is deliberately a fast test rather than a linter rule: it costs
 * milliseconds, so it runs on every commit and it fails the build the moment an
 * agent (or a human) breaks the Controller -&gt; Service -&gt; Repository
 * structure, instead of only mentioning it in a document.
 *
 * <p>
 * These rules do not check themselves. Nothing here proves that a rule still
 * <em>rejects</em> what it is meant to reject, and a rule whose condition is
 * inverted still passes on healthy code, because the wrong direction is usually
 * the one nothing violates. Read a new rule twice; treat a green run as
 * evidence about the code rather than about the rule.
 */
class ArchitectureTest {

	private static final String ROOT = "com.idfinance.financial_transactions";

	private static JavaClasses classes;

	@BeforeAll
	static void importClasses() {
		classes = new ClassFileImporter().withImportOption(ImportOption.Predefined.DO_NOT_INCLUDE_TESTS)
				.importPackages(ROOT);
	}

	/**
	 * ArchUnit 1.5.1 ships no {@code haveMethodsAnnotatedWith}, and the rules below
	 * need it: a bean is recognised as proxied by an annotation on a
	 * <em>method</em>, not on the class.
	 */
	private static DescribedPredicate<JavaClass> haveProxiedMethod(Class<? extends Annotation> proxying) {
		return DescribedPredicate.describe("have a method annotated with @" + proxying.getSimpleName(),
				(javaClass) -> javaClass.getAllMethods().stream()
						.anyMatch(method -> isAnnotatedWith(method, proxying)));
	}

	private static boolean isAnnotatedWith(JavaMethod method, Class<? extends Annotation> annotation) {
		return method.isAnnotatedWith(annotation) || method.isMetaAnnotatedWith(annotation);
	}

	/**
	 * The annotations that make Spring wrap a bean in a proxy, which is exactly the
	 * set of reasons a class may legitimately not be final.
	 *
	 * <p>
	 * {@code @SchedulerLock} belongs here for the same reason as the other three:
	 * it is an AOP aspect, so a final method on a final class cannot be advised and
	 * CGLIB cannot subclass the bean. That annotation cost one debugging session
	 * twice — once on {@code WeeklyCurrencyImport} and once on
	 * {@code ScheduledRatesFetcher} — and both times the symptom was a context that
	 * would not start, taking every scenario in the suite with it rather than the
	 * one that mattered.
	 */
	private static DescribedPredicate<JavaClass> needsAProxy() {
		return haveProxiedMethod(Transactional.class).or(haveProxiedMethod(Cacheable.class))
				.or(haveProxiedMethod(Async.class)).or(haveProxiedMethod(SchedulerLock.class));
	}

	/**
	 * Written as a predicate rather than through {@code beFinal()} /
	 * {@code notHaveModifier(…)}: ArchUnit only offers {@code beFinal()} on fields,
	 * and reading {@code notHaveModifier(FINAL)} as "must not be final" produces
	 * the exact opposite rule, which is a very quiet way to break a build.
	 */
	private static DescribedPredicate<JavaClass> isFinal() {
		return DescribedPredicate.describe("be final",
				(javaClass) -> javaClass.getModifiers().contains(JavaModifier.FINAL));
	}

	/**
	 * MapStruct generates the implementation, so its finality is not ours to
	 * decide. It is a {@code @Component} like any other, hence the explicit
	 * exclusion rather than a silent hole in the rule.
	 */
	private static DescribedPredicate<JavaClass> generatedByMapStruct() {
		return DescribedPredicate.describe("be generated by MapStruct",
				(javaClass) -> javaClass.getSimpleName().endsWith("Impl"));
	}

	@Test
	void controllersMustNotAccessRepositoriesDirectly() {
		ArchRule rule = noClasses().that().resideInAPackage("..controller..").should().dependOnClassesThat()
				.resideInAPackage("..repository..").because("controllers must go through the service layer");
		rule.check(classes);
	}

	@Test
	void servicesMustNotDependOnControllers() {
		ArchRule rule = noClasses().that().resideInAPackage("..service..").should().dependOnClassesThat()
				.resideInAPackage("..controller..").because("the dependency must only ever point inwards");
		rule.check(classes);
	}

	@Test
	void repositoriesMustNotDependOnServices() {
		ArchRule rule = noClasses().that().resideInAPackage("..repository..").should().dependOnClassesThat()
				.resideInAPackage("..service..").because("the dependency must only ever point inwards");
		rule.check(classes);
	}

	@Test
	void controllersMustNotTalkToThePersistenceApiDirectly() {
		ArchRule rule = noClasses().that().resideInAPackage("..controller..").should().dependOnClassesThat()
				.resideInAnyPackage("jakarta.persistence..", "org.springframework.data..", "org.hibernate..")
				.because("persistence belongs behind the repository layer");
		rule.check(classes);
	}

	@Test
	void mappersMustBeMapStructInterfaces() {
		ArchRule rule = classes().that().areAnnotatedWith(org.mapstruct.Mapper.class).should().beInterfaces()
				.because("DTO to entity conversion is generated by MapStruct, never hand written");
		rule.check(classes);
	}

	@Test
	void exceptionHandlersMustLiveInTheExceptionPackage() {
		ArchRule rule = classes().that()
				.areAnnotatedWith(org.springframework.web.bind.annotation.RestControllerAdvice.class).should()
				.resideInAPackage("..exception..")
				.because("there is exactly one place that turns exceptions into ProblemDetail bodies");
		rule.check(classes);
	}

	@Test
	void servicesMustNotDependOnTheWebLayerTypes() {
		ArchRule rule = noClasses().that().resideInAPackage("..service..").should().dependOnClassesThat()
				.resideInAnyPackage("org.springframework.web..", "jakarta.servlet..")
				.because("HTTP concerns stay in the web layer; services must be plain Java");
		rule.check(classes);
	}

	/**
	 * Stateless beans: the spec is graded on concurrent transaction posts, so a
	 * mutable field on a shared bean is a real defect rather than a style question.
	 */
	@Test
	void springBeansMustNotHaveMutableInstanceFields() {
		ArchRule rule = noFields().that().areDeclaredInClassesThat().areAnnotatedWith(Component.class).should()
				.notBeFinal().because("shared Spring beans must be stateless to stay thread safe");
		rule.check(classes);
	}

	/**
	 * A transactional bean has to stay subclassable.
	 *
	 * <p>
	 * Spring proxies {@code @Transactional} beans with CGLIB, and CGLIB refuses to
	 * subclass a final class. Marking one final would not fail the build — it would
	 * quietly take the transactions away, which is the worst possible outcome for a
	 * service whose correctness depends on a row lock. This rule is why the six
	 * services carrying {@code @Transactional} are the only classes in the project
	 * that are not final, and why that is not an oversight to tidy up.
	 */
	@Test
	void transactionalBeansMustRemainProxyable() {
		ArchRule rule = noClasses().that(needsAProxy()).should(ArchConditions.be(isFinal()))
				.because("CGLIB cannot subclass a final class, so the bean would silently lose its "
						+ "transactions, its cache, or its scheduler lock — and the context fails to start "
						+ "with an AopConfigException naming only the class, not the annotation");
		rule.check(classes);
	}

	/**
	 * Everything else is final.
	 *
	 * <p>
	 * A bean nothing proxies has no reason to stay extensible, and {@code final} is
	 * what makes the thread-safety argument in
	 * {@code springBeansMustNotHaveMutableInstanceFields} checkable rather than a
	 * convention. The exemption list is the annotations that do need a proxy.
	 */
	@Test
	void beansMustBeFinalUnlessSomethingProxiesThem() {
		ArchRule rule = classes().that().areAnnotatedWith(Component.class).and(needsAProxy().negate())
				.and(generatedByMapStruct().negate()).should(ArchConditions.be(isFinal()))
				.because("a bean nothing proxies needs no subclassing, and final is what proves it");
		rule.check(classes);
	}

}
