-- Какие задачи по расписанию включены, решается в базе, а не свойством.
--
-- @ConditionalOnProperty вычисляется один раз при старте контекста, поэтому переключатель на
-- свойстве означает перезапуск. Для задач, которые платят внешнему API, это плохо: чтобы не платить,
-- приходится перезапускать приложение. Здесь флаг читается в момент срабатывания, и выключение —
-- это UPDATE, а не рестарт.
--
-- Перезапуск при этом тоже не нужен, потому что единственное, что делает выключенная задача, —
-- возвращается из метода, не позвонив провайдеру. Сама пробуждение раз в неделю не стоит ничего;
-- стоит HTTP-вызов, которого не будет.
--
-- Строки состояния общие для всех реплик. Флаг в памяти процесса действовал бы на ту реплику,
-- где его выключили, и оставлял бы остальные платить — то есть выключатель, который на самом деле
-- не выключает, хуже отсутствующего.
--
-- name — натуральный ключ: на таблицу никто не ссылается, а код обращается к строке по имени,
-- которое и так знает. Суррогатный id здесь был бы колонкой, которую никто не прочитает.

create table scheduled_job
(
    name        varchar(64) primary key,
    enabled     boolean     not null default true,
    description varchar(255) not null,
    -- Нет updated_at: now() по умолчанию срабатывает только на вставке, и при переключении колонка
    -- молча устарела бы. «Кто и когда выключил» берётся из лога задачи, пропустившей запуск, и он
    -- пишется каждый раз — что честнее молчащей даты.
    constraint ck_scheduled_job_known check (name in ('daily-rates', 'weekly-currency-import'))
);

insert into scheduled_job (name, enabled, description)
values ('daily-rates', true,
        'Daily sweep of the rates for every active currency_pair. The specification requires it.'),
       ('weekly-currency-import', true,
        'Re-reads the provider''s currency list, which costs credits and changes about once a year.');
