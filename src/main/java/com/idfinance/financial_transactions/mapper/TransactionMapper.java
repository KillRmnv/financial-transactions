package com.idfinance.financial_transactions.mapper;

import com.idfinance.financial_transactions.dto.TransactionRequest;
import com.idfinance.financial_transactions.dto.TransactionResponse;
import com.idfinance.financial_transactions.dto.TransactionWithLimitResponse;
import com.idfinance.financial_transactions.entity.Currency;
import com.idfinance.financial_transactions.entity.ExpenseTransaction;
import com.idfinance.financial_transactions.service.AcceptedTransaction;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.ReportingPolicy;

/**
 * DTO to entity mapping, generated by MapStruct.
 *
 * <p>
 * Hand-written converters are forbidden by the project convention, and this
 * interface is where the ones that would otherwise be written inside a
 * controller belong. Anything that cannot be expressed declaratively is a
 * {@code default} method here, with named locals instead of positional
 * arguments and a ternary per field.
 */
@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
public interface TransactionMapper {

	/**
	 * Builds an unsaved transaction.
	 *
	 * <p>
	 * Every target is named explicitly, including the ones whose name already
	 * matches. An implicit mapping is a mapping that silently stops working the day
	 * a field is renamed, and the compiler says nothing about it.
	 *
	 * <p>
	 * {@code occurredAt} and {@code occurredMonth} are not taken from the request
	 * body: the caller derives both from the timestamp in the configured timezone,
	 * which is the server's decision and not something the client may assert.
	 * Passing them in as parameters rather than as an inline expression keeps the
	 * generated code free of any dereference of its own. The currency and category
	 * arrive as verified references rather than as raw strings, which is the whole
	 * point of the lookup tables.
	 */
	@Mapping(target = "id", ignore = true)
	@Mapping(target = "accountFrom", source = "request.accountFrom")
	@Mapping(target = "accountTo", source = "request.accountTo")
	@Mapping(target = "sum", source = "request.sum")
	@Mapping(target = "currency", source = "currency")
	@Mapping(target = "categoryId", source = "categoryId")
	@Mapping(target = "occurredAt", source = "occurredAt")
	@Mapping(target = "occurredMonth", source = "occurredMonth")
	@Mapping(target = "sumInLedger", ignore = true)
	@Mapping(target = "appliedRate", ignore = true)
	@Mapping(target = "rateDate", ignore = true)
	@Mapping(target = "limitId", ignore = true)
	@Mapping(target = "limitExceeded", ignore = true)
	@Mapping(target = "flagCalculated", ignore = true)
	ExpenseTransaction toEntity(TransactionRequest request, Currency currency, Long categoryId, Instant occurredAt,
			LocalDate occurredMonth);

	default TransactionResponse toResponse(AcceptedTransaction accepted, ZoneId zone) {
		ExpenseTransaction transaction = accepted.transaction();
		return new TransactionResponse(transaction.getId(), transaction.getAccountFrom(), transaction.getAccountTo(),
				accepted.currencyCode(), transaction.getSum(), accepted.expenseCategory(), at(transaction, zone),
				transaction.getSumInLedger(), transaction.getLimitExceeded(), transaction.isFlagCalculated());
	}

	/**
	 * The answer to "which transactions exceeded the limit".
	 *
	 * <p>
	 * The limit is already resolved by the reporting service, so every one of its
	 * fields is optional in a single place rather than a ternary repeated at each
	 * argument position: a transaction accepted without a rate has no limit to
	 * report.
	 */
	default TransactionWithLimitResponse toResponseWithLimit(ExpenseTransaction transaction, String accountFrom,
			String currencyCode, String expenseCategory, ZoneId zone, OffsetDateTime limitDatetime, BigDecimal limitSum,
			String limitCurrencyShortname) {
		return new TransactionWithLimitResponse(transaction.getId(), accountFrom, transaction.getAccountTo(),
				currencyCode, transaction.getSum(), expenseCategory, at(transaction, zone),
				transaction.getSumInLedger(), transaction.getLimitExceeded(), limitSum, limitDatetime,
				limitCurrencyShortname);
	}

	private static OffsetDateTime at(ExpenseTransaction transaction, ZoneId zone) {
		return at(transaction.getOccurredAt(), zone);
	}

	private static OffsetDateTime at(Instant instant, ZoneId zone) {
		return instant.atZone(zone).toOffsetDateTime();
	}

}
